def test_three_level_imports_lift_each_input_once(tmp_path):
    a = source(
        tmp_path, "a", "inputs:\n  lib-b:\n    url: git://s/lib-b?ref=refs/tags/v1\nimports:\n  - lib-b/devenv\n"
    )
    b = source(tmp_path, "b", "inputs:\n  lib-c:\n    url: git://s/lib-c?ref=refs/tags/v1\nimports:\n  - lib-c\n")
    c = source(tmp_path, "c", "inputs:\n  leaf:\n    url: git://s/leaf?ref=refs/tags/v1\n    flake: false\n")
    (b / "devenv").mkdir()
    (b / "devenv" / "devenv.yaml").write_text(
        "inputs:\n  lib-c:\n    url: git://s/lib-c?ref=refs/tags/v1\nimports:\n  - lib-c\n"
    )
    (a / "devenv").mkdir()
    (a / "devenv" / "devenv.yaml").write_text((a / "devenv.yaml").read_text())
    root = project(
        tmp_path,
        """
        [targets]
        devenv = true
        [inputs]
        lib-a = { url = "git://s/lib-a", ref = "refs/tags/v1" }
        [imports]
        lib-a = "devenv"
        """,
    )
    resolver = FakeResolver(
        {
            "git://s/lib-a?ref=refs/tags/v1": a,
            "git://s/lib-b?ref=refs/tags/v1": b,
            "git://s/lib-c?ref=refs/tags/v1": c,
        }
    )
    result = run(root, resolver)
    text = (root / ".vendomat" / "devenv.yaml").read_text()
    for name in ("lib-a", "lib-b", "lib-c", "leaf"):
        assert text.count(f"\n  {name}:\n") == 1
    assert result.imports == 3
    digest = read_digest(root / ".vendomat" / "digest")
    assert {k for k in digest if k.startswith("import")} == {"import"} or "import" in digest


