def test_a_changed_registry_rewrites_and_the_digest_follows(tmp_path):
    root = project(tmp_path, '[targets]\ndevenv = true\n[inputs]\nd = { url = "path:/x", flake = false }\n')
    run(root, FakeResolver({}))
    first = read_digest(root / ".vendomat" / "digest")
