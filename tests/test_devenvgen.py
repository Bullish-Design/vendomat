TOOL = "0.7.0"


class FakeResolver:
    """Sources are directories under ``tmp_path``; flake children come from a table."""

    def __init__(self, sources: dict[str, Path], children: dict[str, dict[str, dict[str, Any]]] | None = None):
        self.sources = sources
        self.children = children or {}
        self.prefetched: list[str] = []
        self.listed: list[str] = []

    def prefetch(self, url: str) -> Fetched:
        self.prefetched.append(url)
        if url not in self.sources:
            raise NixError(f"fetch {url}: unreachable")
        return Fetched(str(self.sources[url]), "sha256-" + url.replace("/", "_"), None)

    def direct_inputs(self, url: str) -> dict[str, dict[str, Any]]:
        self.listed.append(url)
        return self.children.get(url, {})


def project(tmp_path: Path, toml: str) -> Path:
    root = tmp_path / "ws"
    root.mkdir()
    (root / "vendomat.toml").write_text(textwrap.dedent(toml))
    return root


def source(tmp_path: Path, name: str, yaml: str | None) -> Path:
    path = tmp_path / "src" / name
    path.mkdir(parents=True)
    if yaml is not None:
        (path / "devenv.yaml").write_text(textwrap.dedent(yaml))
    return path


NIXPKGS = "github:NixOS/nixpkgs/e7439b6b14ad3cc35d05608ebca9bce01a25f5f8"


def run(root: Path, resolver: FakeResolver, **kw: Any):
    registry = parse_registry((root / "vendomat.toml").read_text())
    kw.setdefault("update_lock", False)
    return sync_devenv(root, registry, TOOL, resolver, **kw)


def test_the_fragment_has_three_files_and_every_input(tmp_path):
    root = project(
        tmp_path,
        """
        [targets]
        devenv = true
        [inputs]
        data = { url = "path:/x/data", flake = false }
        """,
    )
    result = run(root, FakeResolver({}))
    assert result.changed and not result.skipped
    names = sorted(p.name for p in (root / ".vendomat").iterdir())
    assert names == ["devenv.nix", "devenv.yaml", "digest"]
    text = (root / ".vendomat" / "devenv.yaml").read_text()
    assert "# GENERATED by vendomat 0.7.0" in text
    assert f'url: "{DEFAULT_NIXPKGS_URL}"' in text
    assert "flake: false" in text
    assert any("release default" in n for n in result.notes)


