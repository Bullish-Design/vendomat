def lock_with(**nodes: dict[str, Any]) -> dict[str, Any]:
    return {
        "nodes": {
            "root": {"inputs": {name: name for name in nodes}},
            **nodes,
        },
        "root": "root",
        "version": 7,
    }


def test_lock_problems_names_missing_and_moved_inputs():
    lock = lock_with(
        a={"locked": {"rev": "1" * 40}, "original": {"type": "git", "url": "git://s/a", "ref": "refs/tags/v1"}},
    )
    assert lock_problems(lock, {"a": "git://s/a?ref=refs/tags/v1"}) == []
    moved = lock_problems(lock, {"a": "git://s/a?ref=refs/tags/v2"})
    assert moved and moved[0][0] == "a"
    missing = lock_problems(lock, {"b": "git://s/b?ref=refs/tags/v1"})
    assert missing == [("b", "not in the lock")]
    assert lock_problems(None, {"x": "u"}) == [("x", "no devenv.lock")]


def test_same_source_is_unknown_for_a_form_it_does_not_read():
    assert same_source("flake:foo", {"type": "indirect", "id": "foo"}) is None


def stub_devenv(tmp_path: Path, body: str) -> str:
    script = tmp_path / "devenv-stub"
    script.write_text("#!/bin/sh\n" + textwrap.dedent(body))
    script.chmod(script.stat().st_mode | stat.S_IEXEC)
    return str(script)


GOOD_LOCK = json.dumps(
    lock_with(a={"locked": {"rev": "1" * 40}, "original": {"type": "git", "url": "git://s/a", "ref": "refs/tags/v1"}})
)


def test_ensure_lock_runs_update_when_the_lock_is_missing(tmp_path):
    root = tmp_path / "ws"
    root.mkdir()
    cmd = stub_devenv(tmp_path, f"cat > devenv.lock <<'EOF'\n{GOOD_LOCK}\nEOF\n")
    assert ensure_lock(root, {"a": "git://s/a?ref=refs/tags/v1"}, cmd) is True
    assert ensure_lock(root, {"a": "git://s/a?ref=refs/tags/v1"}, "/no/such/command") is False


def test_ensure_lock_updates_all_when_two_inputs_are_missing(tmp_path):
    root = tmp_path / "ws"
    root.mkdir()
    (root / "devenv.lock").write_text(json.dumps(lock_with()))
    complete = json.dumps(
        lock_with(
            a={"locked": {"rev": "1" * 40}, "original": {"type": "git", "url": "git://s/a", "ref": "refs/tags/v1"}},
            b={"locked": {"rev": "2" * 40}, "original": {"type": "git", "url": "git://s/b", "ref": "refs/tags/v1"}},
        )
    )
    cmd = stub_devenv(tmp_path, f"printf '%s\\n' \"$@\" > argv\ncat > devenv.lock <<'EOF'\n{complete}\nEOF\n")
    assert ensure_lock(root, {"a": "git://s/a?ref=refs/tags/v1", "b": "git://s/b?ref=refs/tags/v1"}, cmd)
    assert (root / "argv").read_text() == "update\n"


def test_a_failed_update_that_exits_zero_is_still_a_failure_and_keeps_the_prior_lock(tmp_path):
    root = tmp_path / "ws"
    root.mkdir()
    prior = json.dumps(lock_with(z={"locked": {"rev": "2" * 40}, "original": {"type": "git", "url": "git://s/z"}}))
    (root / "devenv.lock").write_text(prior)
    # Exit 0, print an error, write nothing: the stock behavior of `devenv update` (NAT-026).
    cmd = stub_devenv(tmp_path, "echo 'error: unable to download git://s/a' >&2\nexit 0\n")
    with pytest.raises(DevenvSyncError) as info:
        ensure_lock(root, {"a": "git://s/a?ref=refs/tags/v1", "z": "git://s/z"}, cmd)
    assert "a: not in the lock" in str(info.value)
    assert "prior devenv.lock is back in place" in str(info.value)
    assert "unable to download" in str(info.value)
    assert (root / "devenv.lock").read_text() == prior


def test_a_partial_lock_from_a_failed_update_is_rolled_back(tmp_path):
    root = tmp_path / "ws"
